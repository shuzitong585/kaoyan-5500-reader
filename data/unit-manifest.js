  function duplicates(values) {
    const seen = new Set(), dup = new Set();
    values.forEach(v => { if (seen.has(v)) dup.add(v); else seen.add(v); });
    return [...dup];
  }

  function inspect() {
    const errors = [];
    const ids = Object.keys(entries);
    if (ids.length !== UNIT_COUNT) errors.push(`Unit 数量应为 ${UNIT_COUNT}，当前为 ${ids.length}。`);
    const owners = new Map();
    ids.forEach(id => {
      const entry = entries[id];
      const words = Array.isArray(entry.officialTargetWords) ? entry.officialTargetWords.map(normalizeWord) : [];
      if (entry.id !== id) errors.push(`${id} 的 entry.id 不一致。`);
      if (!words.length || words.length > WORDS_PER_UNIT) errors.push(`${id} 词数异常：${words.length}。`);
      if (duplicates(words.filter(Boolean)).length) errors.push(`${id} Unit 内重复词。`);
      words.filter(Boolean).forEach(word => {
        if (!owners.has(word)) owners.set(word, []);
        owners.get(word).push(id);
      });
    });
    const cross = [...owners].filter(([, v]) => v.length > 1);
    if (owners.size !== TOTAL_WORDS) errors.push(`全局唯一词应为 ${TOTAL_WORDS}，当前为 ${owners.size}。`);
    if (cross.length) errors.push(`Unit 间重复词：${cross.length} 个。`);
    return { valid: errors.length === 0, errors, lockedUnitCount: ids.length, lockedWordCount: owners.size };
  }

  function validateOfficialUnit(unit) {
    if (unit.status !== "official") return;
    const entry = entries[unit.id] || supplementEntries[unit.id];
    if (!entry) throw new Error(`正式 Unit ${unit.id} 不存在于 Unit Manifest。`);
    const manifestWords = entry.officialTargetWords.map(normalizeWord);
    const unitWords = unit.vocabulary.map(item => normalizeWord(item?.word));
    const unitSet = new Set(unitWords);
    const manifestSet = new Set(manifestWords);
    const problems = [];
    if (unitWords.length !== manifestWords.length) problems.push(`数量应为 ${manifestWords.length}，当前为 ${unitWords.length}`);
    const missing = manifestWords.filter(word => !unitSet.has(word));
    const extra = [...unitSet].filter(word => !manifestSet.has(word));
    if (missing.length) problems.push(`缺少：${missing.join(", ")}`);
    if (extra.length) problems.push(`多出/换入：${extra.join(", ")}`);
    if (duplicates(unitWords.filter(Boolean)).length) problems.push(`重复：${duplicates(unitWords.filter(Boolean)).join(", ")}`);
    if (problems.length) throw new Error(`${unit.id} vocabulary 与正式 Manifest 不一致：${problems.join("；")}。`);
  }

